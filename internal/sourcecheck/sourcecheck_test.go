func TestCheckImportsAndDiagnostics(t *testing.T) {
	tests := []struct {
		name       string
		path       string
		source     string
		wantRule   string
		wantDetail string
	}{
		{
			name:   "domain may use content",
			path:   "internal/tbtd/campaign/campaign.go",
			source: header + "package campaign\nimport _ \"github.com/crawter/too-broke-to-die/internal/tbtd/content\"\n",
		},
		{
			name:       "domain cannot use raylib",
			path:       "internal/tbtd/simulation/world.go",
			source:     header + "package simulation\nimport _ \"github.com/gen2brain/raylib-go/raylib\"\n",
			wantRule:   "dependency-direction",
			wantDetail: "raylib",
		},
		{
			name:       "domain cannot use windows",
			path:       "internal/tbtd/session/session.go",
			source:     header + "package session\nimport _ \"golang.org/x/sys/windows\"\n",
			wantRule:   "dependency-direction",
			wantDetail: "platform",
		},
		{
			name:       "domain cannot use persistence",
			path:       "internal/tbtd/campaign/save.go",
			source:     header + "package campaign\nimport _ \"github.com/crawter/too-broke-to-die/internal/tbtd/persistence\"\n",
			wantRule:   "dependency-direction",
			wantDetail: "persistence",
		},
		{
			name:       "shared code cannot use desktop",
			path:       "internal/tbtd/windows/windows.go",
			source:     header + "package windows\nimport _ \"github.com/crawter/too-broke-to-die/internal/tbtd/desktop/input\"\n",
			wantRule:   "dependency-direction",
			wantDetail: "desktop",
		},
		{
			name:       "adapter cannot use live world",
			path:       "internal/tbtd/desktop/render/render.go",
			source:     header + "package render\nimport _ \"github.com/crawter/too-broke-to-die/internal/tbtd/simulation\"\n",
			wantRule:   "dependency-direction",
			wantDetail: "session",
		},
		{
			name:       "entrypoint cannot wire domain directly",
			path:       "cmd/tbtd/main.go",
			source:     header + "package main\nimport _ \"github.com/crawter/too-broke-to-die/internal/tbtd/campaign\"\n",
			wantRule:   "dependency-direction",
			wantDetail: "composition root",
		},
		{
			name:   "composition root may wire persistence",
			path:   "internal/tbtd/desktop/desktop.go",
			source: header + "package desktop\nimport _ \"github.com/crawter/too-broke-to-die/internal/tbtd/persistence\"\n",
		},
		{
			name:   "comments and strings are not imports",
			path:   "internal/tbtd/campaign/text.go",
			source: header + "package campaign\n// import \"github.com/gen2brain/raylib-go/raylib\"\nconst text = \"import windows\"\n",
		},
		{
			name:       "missing header",
			path:       "internal/tbtd/content/content.go",
			source:     "package content\n",
			wantRule:   "header",
			wantDetail: "copyright",
		},
		{
			name:   "generated source needs no selected header",
			path:   "internal/tbtd/content/generated.go",
			source: "// Code generated by example; DO NOT EDIT.\n\npackage content\n",
		},
		{
			name:       "generated source still obeys dependency direction",
			path:       "internal/tbtd/content/generated.go",
			source:     "// Code generated by example; DO NOT EDIT.\n\npackage content\nimport _ \"github.com/gen2brain/raylib-go/raylib\"\n",
			wantRule:   "dependency-direction",
			wantDetail: "raylib",
		},
		{
			name:   "build tag before header",
			path:   "internal/tbtd/windows/profile_windows.go",
			source: "//go:build windows\n\n" + header + "package windows\n",
		},
		{
			name:       "invalid build tag",
			path:       "internal/tbtd/windows/profile_windows.go",
			source:     "//go:build (\n\n" + header + "package windows\n",
			wantRule:   "build-constraint",
			wantDetail: "invalid",
		},
		{
			name:       "malformed source",
			path:       "internal/tbtd/content/bad.go",
			source:     header + "package content\nfunc broken( {\n",
			wantRule:   "syntax",
			wantDetail: "bad.go",
		},
		{
			name:       "catch-all package",
			path:       "internal/misc/misc.go",
			source:     header + "package misc\n",
			wantRule:   "package",
			wantDetail: "catch-all",
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			writeFixture(t, root, test.path, test.source)
			diagnostics, err := Check(context.Background(), root)
			if err != nil {
				t.Fatal(err)
			}
			if test.wantRule == "" {
				if len(diagnostics) != 0 {
					t.Fatalf("unexpected diagnostics: %v", diagnostics)
				}
				return
			}
			for _, diagnostic := range diagnostics {
				if diagnostic.Rule == test.wantRule &&
					diagnostic.File == test.path &&
					strings.Contains(diagnostic.Message, test.wantDetail) &&
					strings.Contains(diagnostic.String(), test.path) {
					return
				}
			}
			t.Fatalf("missing %s diagnostic containing %q: %v", test.wantRule, test.wantDetail, diagnostics)
		})
	}
}

func TestModuleDirections(t *testing.T) {
	tests := []struct {
		from    string
		to      string
		allowed bool
	}{
		{"campaign", "content", true},
		{"campaign", "session", false},
		{"campaign", "simulation", false},
		{"simulation", "content", true},
		{"simulation", "campaign", true},
		{"simulation", "session", false},
		{"session", "content", true},
		{"session", "campaign", true},
		{"session", "simulation", true},
		{"session", "persistence", false},
		{"persistence", "session", true},
		{"persistence", "campaign", true},
		{"persistence", "windows", true},
		{"persistence", "simulation", false},
		{"windows", "session", false},
		{"diagnostics", "campaign", false},
	}
	for _, test := range tests {
		t.Run(test.from+"_to_"+test.to, func(t *testing.T) {
			root := t.TempDir()
			path := "internal/tbtd/" + test.from + "/fixture.go"
			source := header + "package " + test.from + "\nimport _ \"" + modulePath + "/internal/tbtd/" + test.to + "\"\n"
			writeFixture(t, root, path, source)
			diagnostics, err := Check(context.Background(), root)
			if err != nil {
				t.Fatal(err)
			}
			if test.allowed && len(diagnostics) != 0 {
				t.Fatalf("permitted dependency rejected: %v", diagnostics)
			}
			if !test.allowed && (len(diagnostics) != 1 || diagnostics[0].Rule != "dependency-direction") {
				t.Fatalf("forbidden dependency not diagnosed: %v", diagnostics)
			}
		})
	}
}

func TestInstrumentation(t *testing.T) {
	prefix := header + `package example
import (
	"context"
	monkit "github.com/spacemonkeygo/monkit/v3"
)
var mon = monkit.Package()
`
	tests := []struct {
		name     string
		path     string
		source   string
		wantFail bool
	}{
		{
			name:   "deferred task",
			path:   "internal/example/example.go",
			source: prefix + "func work(ctx context.Context) (err error) { defer mon.Task()(&ctx)(&err); return other(ctx) }\n",
		},
		{
			name:     "missing defer",
			path:     "internal/example/example.go",
			source:   prefix + "func work(ctx context.Context) (err error) { return other(ctx) }\n",
			wantFail: true,
		},
		{
			name:     "immediate task is not deferred",
			path:     "internal/example/example.go",
			source:   prefix + "func work(ctx context.Context) (err error) { mon.Task()(&ctx)(&err); return other(ctx) }\n",
			wantFail: true,
		},
		{
			name:     "unnamed error",
			path:     "internal/example/example.go",
			source:   prefix + "func work(ctx context.Context) error { return other(ctx) }\n",
			wantFail: true,
		},
		{
			name:   "no error result",
			path:   "internal/example/example.go",
			source: prefix + "func work(ctx context.Context) { defer mon.Task()(&ctx)(nil); other(ctx) }\n",
		},
		{
			name:   "trivial accessor",
			path:   "internal/example/example.go",
			source: prefix + "func value(ctx context.Context) int { return 1 }\n",
		},
		{
			name:   "fixed signature",
			path:   "internal/example/example.go",
			source: prefix + "func (v value) String() string { return otherString() }\n",
		},
		{
			name:   "reader interface signature",
			path:   "internal/example/example.go",
			source: prefix + "func (v value) Read(p []byte) (int, error) { return read(p) }\n",
		},
		{
			name:     "reader name with incompatible signature",
			path:     "internal/example/example.go",
			source:   prefix + "func (v value) Read(p int) int { return read(p) }\n",
			wantFail: true,
		},
		{
			name: "local interface implementation",
			path: "internal/example/example.go",
			source: prefix + "type visitor interface { Visit(int) error; Close() error }\n" +
				"func (v value) Visit(n int) error { return visit(n) }\n" +
				"func (v value) Close() error { return closeValue() }\n",
		},
		{
			name:     "incomplete local interface",
			path:     "internal/example/example.go",
			source:   prefix + "type visitor interface { Visit(int) error; Close() error }\nfunc (v value) Visit(n int) error { return visit(n) }\n",
			wantFail: true,
		},
		{
			name: "named callback",
			path: "internal/example/example.go",
			source: prefix + "func visit(n int) error { return process(n) }\n" +
				"func work(ctx context.Context) { defer mon.Task()(&ctx)(nil); walk(visit) }\n",
		},
		{
			name:     "ordinary operation needs context",
			path:     "internal/example/example.go",
			source:   prefix + "func load() error { return readFile() }\n",
			wantFail: true,
		},
		{
			name:     "unrelated method is not a fixed signature",
			path:     "internal/example/example.go",
			source:   prefix + "func (v value) Load() error { return readFile() }\n",
			wantFail: true,
		},
		{
			name: "per-item helper called only in loop",
			path: "internal/example/example.go",
			source: prefix + "func item(values []int) int { total := 0; for _, value := range values { total += value }; return total }\n" +
				"func work(ctx context.Context) { defer mon.Task()(&ctx)(nil); for range values { item(values) } }\n",
		},
		{
			name: "io helper called only in loop",
			path: "internal/example/example.go",
			source: prefix + "func item() { os.ReadFile(\"fixture\") }\n" +
				"func work(ctx context.Context) { defer mon.Task()(&ctx)(nil); for range values { item() } }\n",
			wantFail: true,
		},
		{
			name: "unknown helper call may perform io",
			path: "internal/example/example.go",
			source: prefix + "func item() { readFile() }\n" +
				"func work(ctx context.Context) { defer mon.Task()(&ctx)(nil); for range values { item() } }\n",
			wantFail: true,
		},
		{
			name: "helper also called outside loop",
			path: "internal/example/example.go",
			source: prefix + "func item(values []int) int { total := 0; for _, value := range values { total += value }; return total }\n" +
				"func work(ctx context.Context) { defer mon.Task()(&ctx)(nil); item(values); for range values { item(values) } }\n",
			wantFail: true,
		},
		{
			name:   "test is exempt",
			path:   "internal/example/example_test.go",
			source: prefix + "func work(ctx context.Context) error { return other(ctx) }\n",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			writeFixture(t, root, test.path, test.source)
			diagnostics, err := Check(context.Background(), root)
			if err != nil {
				t.Fatal(err)
			}
			found := false
			for _, diagnostic := range diagnostics {
				if diagnostic.Rule == "instrumentation" || diagnostic.Rule == "context" {
					found = true
				} else {
					t.Errorf("unexpected diagnostic: %s", diagnostic)
				}
			}
			if found != test.wantFail {
				t.Fatalf("instrumentation failure = %v, want %v: %v", found, test.wantFail, diagnostics)
			}
		})
	}
}

func TestInstrumentationHandleAcrossFiles(t *testing.T) {
	handle := header + `package example
import monkit "github.com/spacemonkeygo/monkit/v3"
var mon = monkit.Package()
`
	operation := header + `package example
import "context"
func work(ctx context.Context) (err error) {
	defer mon.Task()(&ctx)(&err)
	return other(ctx)
}
`
	tests := []struct {
		name       string
		files      map[string]string
		wantHandle bool
	}{
		{
			name: "shared package handle",
			files: map[string]string{
				"handle.go": handle,
				"work.go":   operation,
			},
			wantHandle: true,
		},
		{
			name: "mutually exclusive tags do not provide a handle",
			files: map[string]string{
				"handle.go": "//go:build linux\n\n" + handle,
				"work.go":   "//go:build windows\n\n" + operation,
			},
		},
		{
			name: "filename constraints do not provide a handle",
			files: map[string]string{
				"handle_linux.go": handle,
				"work_windows.go": operation,
			},
		},
		{
			name: "complementary handles cover all configurations",
			files: map[string]string{
				"handle_windows.go": handle,
				"handle_other.go":   "//go:build !windows\n\n" + handle,
				"work.go":           operation,
			},
			wantHandle: true,
		},
		{
			name: "test handle cannot satisfy production",
			files: map[string]string{
				"handle_test.go": handle,
				"work.go":        operation,
			},
		},
		{
			name: "other package cannot supply a handle",
			files: map[string]string{
				"handle.go": strings.Replace(handle, "package example", "package other", 1),
				"work.go":   operation,
			},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			for name, source := range test.files {
				writeFixture(t, root, "internal/example/"+name, source)
			}
			diagnostics, err := Check(context.Background(), root)
			if err != nil {
				t.Fatal(err)
			}
			missing := false
			for _, diagnostic := range diagnostics {
				if diagnostic.Rule == "instrumentation" && strings.Contains(diagnostic.Message, "handle") {
					missing = true
				} else {
					t.Errorf("unexpected diagnostic: %s", diagnostic)
				}
			}
			if missing == test.wantHandle {
				t.Fatalf("missing handle = %v, want available = %v: %v", missing, test.wantHandle, diagnostics)
			}
		})
	}
}

func TestCheckerSources(t *testing.T) {
	root := filepath.Join("..", "..")
	diagnostics, err := Check(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	for _, diagnostic := range diagnostics {
		if strings.HasPrefix(diagnostic.File, "internal/sourcecheck/") ||
			strings.HasPrefix(diagnostic.File, "cmd/sourcecheck/") {
			t.Errorf("checker source diagnostic: %s", diagnostic)
		}
	}
}

func TestCheckSkipsFixturesButChecksOtherBuildTargets(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "testdata/bad.go", "not Go")
	writeFixture(t, root, "vendor/example/bad.go", "not Go")
	writeFixture(t, root, "internal/tbtd/campaign/platform_windows.go",
		"//go:build windows\n\n"+header+"package campaign\nimport _ \"github.com/gen2brain/raylib-go/raylib\"\n")

	diagnostics, err := Check(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	if len(diagnostics) != 1 || diagnostics[0].Rule != "dependency-direction" {
		t.Fatalf("unexpected diagnostics: %v", diagnostics)
	}
}

func TestCheckCanceled(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := Check(ctx, t.TempDir()); err == nil {
		t.Fatal("expected cancellation")
	}
}

func writeFixture(t *testing.T, root, path, source string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
}
